/*
 * RC Cars — PS Vita track viewer / driving test.
 *
 * Renders a converted track and car through vitaGL's fixed-function pipeline.
 * The original engine is Direct3D 8 fixed-function with no shaders at all,
 * which maps almost one-to-one onto vitaGL — that is why this port is
 * tractable at all.
 *
 * Handling is the GAME'S OWN transcribed model -- rb.c + contact.c + collide.c,
 * data from rb_data.h, camera from cam.c, stepped at a FIXED 1/60 regardless of
 * the frame rate (see rbcar.h). It is the only model: physics.c, the arcade
 * placeholder, is no longer reachable from anywhere.
 * See rccars_re/PHYSICS.md.
 *
 * The car spawns at the track's real race start, taken from that track's own
 * Players/Player instance (tracks.h, generated by rccars_re/gen_tracks.py) --
 * position, heading, and the car the track starts with. It is NOT held there:
 * rb_car.frozen, the engine's start-line hold, is unusable in this port because
 * the rest damper is gated on !frozen, so a held car has nothing damping roll
 * and wanders between 1 and 19 degrees of tilt indefinitely. A free-rolling car
 * on a slope rolls, which is what a real one does.
 *
 * The visual subsystems are the game's own too: the projected car shadow
 * (shadow.c, shdAddSource type 3), the animated water (water.c, WaterLOD) and
 * the checkpoint arrows (checkpoint.c, anim_cp). SQUARE turns all three off.
 *
 * Controls:
 *   R trigger  throttle          L trigger  brake / reverse
 *   CROSS      boost             CIRCLE     jump / right the car
 *   left stick steer             right stick camera orbit (springs back)
 *   START      menu: track, car, tuning parts, texture quality, quit
 *   SQUARE     toggle shadow + water animation + checkpoint arrows
 *   SELECT     toggle free-fly camera
 *
 * CIRCLE is the game's own Jump action -- action 6 of the eight the original's
 * input layer binds (the table at 0x004e4188 names them Boost, Left, Right,
 * Forw, Back, JUMP, Brake, Reset). On its wheels the car hops; on its roof or
 * its side the same button rights it where it stands. See rb_car_jump.
 */

