static void perspective(float fovy, float aspect, float zn, float zf)
{
    float fh = tanf(fovy * 0.5f * DEG) * zn;
    glFrustum(-fh * aspect, fh * aspect, -fh, fh, zn, zf);
}

/* The camera's right and up in WORLD space, for the particle billboards. For an
   orthonormal view rotation R (column-vector, v_eye = R*v_world) the eye-space
   axes in world coordinates are R's ROWS, so these are rows 0 and 1 of Rx*Ry --
   the same product env_normal_matrix builds. */
static void cam_basis(float vpitch, float vyaw, float right[3], float up[3])
{
    float cp = cosf(vpitch * DEG), sp = sinf(vpitch * DEG);
    float cy = cosf(-vyaw * DEG), sy = sinf(-vyaw * DEG);

    right[0] = cy;        right[1] = 0.f; right[2] = sy;
    up[0] = sp * sy;      up[1] = cp;     up[2] = -sp * cy;
}

/*
 * The 3x3 that takes a MODEL-space normal to VIEW space, for the env-map glance.
 *
 * Built rather than read back out of GL, and built the long way on purpose --
 * this is the fourth transform in this port whose convention matters, and the
 * other three all went wrong when they were assumed. The view is laid down as
 * glRotatef(vpitch, X) then glRotatef(-vyaw, Y), which in GL's COLUMN-vector
 * terms is Rx*Ry; every matrix in this port is row-major ROW-vector, whose
 * rotation is that product transposed. The car's own matrix is already in that
 * convention (rbcar_matrix), so it composes on the left.
 */
static void env_normal_matrix(const float *carm, float vpitch, float vyaw,
                              float out[9])
{
    float cp = cosf(vpitch * DEG), sp = sinf(vpitch * DEG);
    float cy = cosf(-vyaw * DEG), sy = sinf(-vyaw * DEG);
    const float Rx[9] = { 1.f, 0.f, 0.f,  0.f, cp, -sp,  0.f, sp, cp };
    const float Ry[9] = { cy, 0.f, sy,  0.f, 1.f, 0.f,  -sy, 0.f, cy };
    float rxry[9], v3[9], c3[9];
    int r, c, k;

    for (r = 0; r < 3; r++)
        for (c = 0; c < 3; c++) {
            float s = 0.f;
            for (k = 0; k < 3; k++)
                s += Rx[r * 3 + k] * Ry[k * 3 + c];
            rxry[r * 3 + c] = s;
        }
    for (r = 0; r < 3; r++)
        for (c = 0; c < 3; c++)
            v3[r * 3 + c] = rxry[c * 3 + r];        /* the transpose */
    for (r = 0; r < 3; r++)
        for (c = 0; c < 3; c++)
            c3[r * 3 + c] = carm[r * 4 + c];
    for (r = 0; r < 3; r++)
        for (c = 0; c < 3; c++) {
            float s = 0.f;
            for (k = 0; k < 3; k++)
                s += c3[r * 3 + k] * v3[k * 3 + c];
            out[r * 3 + c] = s;
        }
}

